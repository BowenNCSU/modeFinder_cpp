"""Write report.md from the CSV files simulate.py leaves in a run directory.

    python simulations/stock_mode_quantile/report.py results/run_<timestamp>
"""

import csv
import json
import os
import sys
from collections import defaultdict

import numpy as np

NUMERIC = {"window", "cost_bps", "final_value", "total_return", "annual_return",
           "max_drawdown", "sharpe", "trades", "round_trips", "win_rate",
           "avg_trip_return", "time_in_market", "trades_per_ticker", "beat_bh",
           "horizon", "prob", "coverage", "bars", "bars_per_day", "median_close"}


def read_csv(path):
    with open(path, newline="") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        for k in r:
            if k in NUMERIC and r[k] != "":
                r[k] = float(r[k])
    return rows


def pct(x, digits=1):
    return "–" if x is None or x != x else f"{100 * x:.{digits}f}%"


def num(x, digits=2):
    return "–" if x is None or x != x else f"{x:.{digits}f}"


def stamp(s):
    s = str(s)
    return f"{s[:4]}-{s[4:6]}-{s[6:8]} {s[8:10]}:{s[10:12]}" if len(s) >= 12 else s


def table(header, rows):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def combo(r):
    if r["method"] == "buy&hold":
        return "buy & hold"
    return f"{r['rule']} · {r['field']} · {int(r['window'])} · {r['method']}"


def mean(xs):
    xs = [x for x in xs if x == x]
    return float(np.mean(xs)) if xs else float("nan")


def portfolio_table(rows):
    return table(
        ["#", "rule · field · window · method", "final value", "return",
         "annual", "max DD", "Sharpe", "trades/ticker", "in market",
         "win rate", "beats B&H"],
        [[i, combo(r), f"${r['final_value']:,.0f}", pct(r["total_return"]),
          pct(r["annual_return"]), pct(r["max_drawdown"]), num(r["sharpe"]),
          num(r["trades_per_ticker"], 0), pct(r["time_in_market"], 0),
          pct(r["win_rate"], 0), pct(r["beat_bh"], 0)]
         for i, r in enumerate(rows, 1)])


def marginal(rows, key, bh):
    groups = defaultdict(list)
    for r in rows:
        groups[r[key]].append(r)
    out = []
    for k in sorted(groups, key=lambda k: (isinstance(k, str), k)):
        g = groups[k]
        best = max(g, key=lambda r: r["total_return"])
        out.append([int(k) if key == "window" else k, len(g),
                    pct(mean([r["total_return"] for r in g])),
                    pct(best["total_return"]),
                    num(mean([r["sharpe"] for r in g])),
                    pct(mean([r["max_drawdown"] for r in g])),
                    num(mean([r["trades_per_ticker"] for r in g]), 0),
                    pct(mean([r["total_return"] > bh for r in g]), 0)])
    return table([key, "combos", "mean return", "best return", "mean Sharpe",
                  "mean max DD", "trades/ticker", "beat B&H portfolio"], out)


def write_report(out_dir):
    cfg = json.load(open(os.path.join(out_dir, "config.json")))
    sel = read_csv(os.path.join(out_dir, "selection.csv"))
    per = read_csv(os.path.join(out_dir, "per_ticker.csv"))
    port = read_csv(os.path.join(out_dir, "portfolio.csv"))
    cal_path = os.path.join(out_dir, "calibration.csv")
    cal = read_csv(cal_path) if os.path.exists(cal_path) else []
    costs = sorted({r["cost_bps"] for r in port})
    main_cost = costs[-1]                 # report with costs unless only 0
    L = []
    w = L.append

    starts = sorted(str(s["trade_start"]) for s in sel)
    ends = sorted(str(s["last"]) for s in sel)
    w("# Rolling mode / quantile trading simulation\n")
    w("Generated by `simulate.py` and `report.py`; the request is in "
      "`PROMPT.md`.\n")
    w("## Setup\n")
    w(f"- **Data:** 5-minute bars from `{cfg['data']}`.")
    w(f"- **Tickers:** {sum(s['kind'] == 'stock' for s in sel)} stocks and "
      f"{sum(s['kind'] == 'etf' for s in sel)} ETFs, picked at random "
      f"(seed {cfg['seed']}) among files with at least {cfg['min_bars']} bars, "
      f"a median close of at least ${cfg['min_price']:g} and a median dollar "
      f"volume of at least ${cfg['min_dollar_volume']:,.0f} per bar.")
    w(f"- **Period:** trading starts once the longest window has filled "
      f"({stamp(starts[0])} to {stamp(starts[-1])}, by ticker) and runs to the "
      f"end of each file ({stamp(ends[0])} to {stamp(ends[-1])}).")
    w(f"- **Capital:** ${cfg['capital']:,.0f} per ticker. The portfolio splits "
      f"${cfg['capital']:,.0f} equally across the tickers, and each part trades "
      "on its own.")
    w(f"- **Rolling fit:** at {'every bar' if cfg['step'] == 1 else 'every %d bars' % cfg['step']}, "
      "the window drops its oldest bar, adds the newest, and is refitted with "
      "`modefinder.ModeFinder`. Bernstein uses the support [min − "
      f"{cfg['pad']:g}·range, max + {cfg['pad']:g}·range] of the window, and "
      "kernel uses R's `density()` defaults.")
    w(f"- **Grid:** price field {', '.join(cfg['fields'])}; window "
      f"{', '.join(str(x) for x in cfg['windows'])} bars (78 bars ≈ one "
      f"trading day); method {', '.join(cfg['methods'])}; rule "
      f"{', '.join(cfg['rules'])}; cost {', '.join(f'{c:g}' for c in costs)} bps "
      "per buy or sell.")
    w("- **Rules:** long only, all in or all out. *mode* buys when the close "
      "is below the fitted mode and sells when it is above. *median* does "
      "the same with the fitted median. *qLL/qUU* buys below the LL% "
      "quantile and sells above the UU% quantile, holding in between.")
    w("- **Execution:** the decision uses the close of bar t and a fit on bars "
      "up to t, and fills at the open of bar t + 1. There is no look-ahead.")
    w("")

    w("## Summary\n")
    by_cost = {}
    for cost in costs:
        rows = [r for r in port if r["cost_bps"] == cost]
        strat = sorted((r for r in rows if r["method"] != "buy&hold"),
                       key=lambda r: -r["total_return"])
        by_cost[cost] = (strat, next(r for r in rows if r["method"] == "buy&hold"))
    for cost in sorted(costs):
        strat, bhr = by_cost[cost]
        best = strat[0]
        w(f"- **{cost:g} bps per trade:** the best combination is *{combo(best)}*, "
          f"which returns {pct(best['total_return'])} with a max drawdown of "
          f"{pct(best['max_drawdown'])}. Buy and hold returns "
          f"{pct(bhr['total_return'])}. "
          f"{sum(r['total_return'] > 0 for r in strat)} of {len(strat)} "
          f"combinations make money, and "
          f"{sum(r['total_return'] > bhr['total_return'] for r in strat)} beat "
          "buy and hold.")
    if len(costs) > 1:
        lo, hi = by_cost[costs[0]][0], by_cost[costs[-1]][0]
        key = lambda r: (r["field"], r["window"], r["method"], r["rule"])
        hi_by = {key(r): r for r in hi}
        drag = defaultdict(list)
        for r in lo:
            drag[r["rule"]].append(r["total_return"] - hi_by[key(r)]["total_return"])
        w(f"- **Cost drag:** going from {costs[0]:g} to {costs[-1]:g} bps lowers "
          "the mean portfolio return by "
          + ", ".join(f"{pct(mean(v))} ({k})" for k, v in
                      sorted(drag.items(), key=lambda kv: -mean(kv[1])))
          + ". The rules that trade most lose most.")
    strat = by_cost[main_cost][0]
    w(f"- **Exposure:** the strategies are in the market "
      f"{pct(mean([r['time_in_market'] for r in strat]), 0)} of the time on "
      "average. Part of any lead over buy and hold comes from being in cash "
      "while prices fall, not from timing.")
    if cal:
        for h in sorted({int(r["horizon"]) for r in cal}):
            lo5 = mean([r["coverage"] for r in cal if r["horizon"] == h and r["prob"] == 0.05])
            hi95 = mean([1 - r["coverage"] for r in cal if r["horizon"] == h and r["prob"] == 0.95])
            w(f"- **Calibration, {h} bar{'s' if h > 1 else ''} ahead:** "
              f"{pct(lo5, 0)} of future closes fall below the predicted P05 and "
              f"{pct(hi95, 0)} rise above P95, against 5% each.")
    w("")

    w("## Tickers\n")
    bh = {(r["ticker"], r["cost_bps"]): r for r in per if r["method"] == "buy&hold"}
    w(table(["ticker", "kind", "bars", "bars/day", "first bar", "last bar",
             "median close", "buy & hold"],
            [[s["ticker"], s["kind"], int(s["bars"]), num(s["bars_per_day"], 0),
              stamp(s["first"]), stamp(s["last"]), f"${s['median_close']:,.2f}",
              pct(bh[(s["ticker"], main_cost)]["total_return"])] for s in sel]))
    w("")

    for cost in sorted(costs, reverse=True):
        rows = [r for r in port if r["cost_bps"] == cost]
        strat = sorted((r for r in rows if r["method"] != "buy&hold"),
                       key=lambda r: -r["total_return"])
        bhr = next(r for r in rows if r["method"] == "buy&hold")
        w(f"## Portfolio ranking, {cost:g} bps per trade\n")
        w(f"Buy and hold returns {pct(bhr['total_return'])} (Sharpe "
          f"{num(bhr['sharpe'])}, max drawdown {pct(bhr['max_drawdown'])}). "
          f"{sum(r['total_return'] > bhr['total_return'] for r in strat)} of "
          f"{len(strat)} combinations beat it. Sharpe uses daily portfolio "
          "returns, annualized with √252.\n")
        top = strat[:15] + [bhr]
        w("**Top 15**\n")
        w(portfolio_table(top))
        w("\n**Bottom 5**\n")
        w(portfolio_table(strat[-5:]))
        w("")

    rows = [r for r in port if r["cost_bps"] == main_cost and r["method"] != "buy&hold"]
    bh_ret = next(r for r in port if r["cost_bps"] == main_cost
                  and r["method"] == "buy&hold")["total_return"]
    w(f"## Effect of each parameter ({main_cost:g} bps)\n")
    w("Each row averages the portfolio results over every combination of the "
      "other parameters.\n")
    for key in ("rule", "window", "method", "field"):
        w(f"**{key}**\n")
        w(marginal(rows, key, bh_ret))
        w("")
    w("**Rule × window, mean portfolio return**\n")
    rules = [r for r in cfg["rules"]]
    wins = sorted({int(r["window"]) for r in rows})
    grid = defaultdict(list)
    for r in rows:
        grid[(r["rule"], int(r["window"]))].append(r["total_return"])
    w(table(["rule"] + [f"{x} bars" for x in wins],
            [[ru] + [pct(mean(grid[(ru, x)])) for x in wins] for ru in rules]))
    w("")

    w(f"## Best combination per ticker ({main_cost:g} bps)\n")
    out = []
    for s in sel:
        mine = [r for r in per if r["ticker"] == s["ticker"]
                and r["cost_bps"] == main_cost and r["method"] != "buy&hold"]
        b = max(mine, key=lambda r: r["total_return"])
        x = bh[(s["ticker"], main_cost)]
        out.append([s["ticker"], combo(b), pct(b["total_return"]),
                    pct(b["max_drawdown"]), int(b["trades"]),
                    pct(x["total_return"]), pct(x["max_drawdown"]),
                    pct(mean([r["total_return"] > x["total_return"] for r in mine]), 0)])
    w(table(["ticker", "best rule · field · window · method", "return",
             "max DD", "trades", "B&H return", "B&H max DD",
             "combos beating B&H"], out))
    w("")

    if cal:
        w("## Calibration of the predicted distribution\n")
        w("Share of future closes, h bars ahead, at or below each predicted "
          "quantile, averaged over tickers and price fields. A well-calibrated "
          "forecast matches the column header.\n")
        probs = sorted({r["prob"] for r in cal})
        g = defaultdict(list)
        for r in cal:
            g[(r["method"], int(r["window"]), int(r["horizon"]), r["prob"])].append(r["coverage"])
        keys = sorted({k[:3] for k in g}, key=lambda k: (k[2], k[0], k[1]))
        w(table(["method", "window", "h"] + [f"P{100 * p:02.0f}" for p in probs],
                [[m, wi, h] + [pct(mean(g[(m, wi, h, p)]), 0) for p in probs]
                 for m, wi, h in keys]))
        w("")

    w("## Caveats\n")
    w("- **In-sample choice:** the best combination is picked on the same "
      "history it is scored on. Its edge over the others is an optimistic "
      "estimate; check it on another period or another sample of tickers.")
    w("- **Few tickers:** the sample is small and random, so a few tickers "
      "can drive the portfolio numbers.")
    w("- **Costs and fills:** fills at the next bar's open with a flat cost "
      "per trade. Spreads, slippage and market impact on illiquid names are "
      "not modelled beyond that.")
    w("- **Prices:** dividends are ignored and the data may have survivorship "
      "bias. Gaps between trading days count as one bar.")
    w("- **Cash:** idle cash earns nothing, and a long-only rule is out of "
      "the market part of the time, which lowers its return in a rising "
      "market.")
    w("")
    w(f"Run time {cfg['run_seconds']:.0f} s, modefinder {cfg['modefinder_version']}. "
      "The CSV files next to this report hold every number above.")

    path = os.path.join(out_dir, "report.md")
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
    return path


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    print(write_report(sys.argv[1]))
