"""Write report.md from the CSV files simulate.py leaves in a run directory.

    python simulations/stock_mode_quantile/report.py results/run_<timestamp>
"""

import csv
import json
import os
import sys

import numpy as np

TEXT = {"ticker", "kind", "path", "first", "trade_start", "last", "combo", "field"}


def read_csv(path):
    with open(path, newline="") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        for k in r:
            if k not in TEXT and r[k] != "":
                r[k] = float(r[k])
    return rows


def pct(x, digits=1):
    return "–" if x is None or x != x else f"{100 * x:.{digits}f}%"


def num(x, digits=2):
    return "–" if x is None or x != x else f"{x:.{digits}f}"


def stamp(s):
    s = str(s)
    return f"{s[:4]}-{s[4:6]}-{s[6:8]} {s[8:10]}:{s[10:12]}" if len(s) >= 12 else s


def table(header, rows):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def ranking_table(rows, fields):
    return table(
        ["rank", "ticker", "kind", "mean return"] + [f"return ({f})" for f in fields]
        + ["max DD", "Sharpe", "trades", "in market", "B&H return", "vs B&H"],
        [[int(r["rank"]), r["ticker"] + (" ⚠" if r["jump_flag"] else ""), r["kind"],
          pct(r["mean_return"])] + [pct(r[f"return_{f}"]) for f in fields]
         + [pct(r["mean_max_drawdown"]), num(r["mean_sharpe"]),
            num(r["mean_trades"], 0), pct(r["mean_time_in_market"], 0),
            pct(r["bh_return"]), pct(r["excess_vs_bh"])] for r in rows])


def write_report(out_dir):
    cfg = json.load(open(os.path.join(out_dir, "config.json")))
    sel = read_csv(os.path.join(out_dir, "selection.csv"))
    port = read_csv(os.path.join(out_dir, "portfolio.csv"))
    rank = read_csv(os.path.join(out_dir, "ranking.csv"))
    fields = list(cfg["fields"])
    combos = [r for r in port if r["combo"] != "buy & hold"]
    bhp = next(r for r in port if r["combo"] == "buy & hold")
    n = len(rank)
    mean_ret = np.array([r["mean_return"] for r in rank])
    excess = np.array([r["excess_vs_bh"] for r in rank])
    flagged = [r for r in rank if r["jump_flag"]]
    L = []
    w = L.append

    w("# Top-3 combinations on a large sample\n")
    w("Generated by `simulate.py` and `report.py`; the request is in "
      "`PROMPT.md`.\n")
    w("## Setup\n")
    w(f"- **Combinations:** the three that ranked first, with 2 bps per trade, "
      "in the second round (`results/run_20261019_seed2027`). Each buys when "
      f"the close falls below the fitted {pct(cfg['buy_quantile'], 0)} quantile "
      f"and sells when it rises above the fitted {pct(cfg['sell_quantile'], 0)} "
      f"quantile of the last {cfg['window']} bars (about 20 trading days), "
      f"fitted with `modefinder.ModeFinder(..., smooth_option=\"{cfg['method']}\")`. "
      f"They differ only in the price field: {', '.join(fields)}.")
    w(f"- **Tickers:** {n} picked at random (seed {cfg['seed']}) from "
      f"{cfg['eligible']} eligible files out of {cfg['files']}: "
      f"{sum(s['kind'] == 'stock' for s in sel)} stocks and "
      f"{sum(s['kind'] == 'etf' for s in sel)} ETFs. Eligible means at least "
      f"{cfg['min_bars']} bars, a median close of at least ${cfg['min_price']:g} "
      f"and a median dollar volume of at least ${cfg['min_dollar_volume']:,.0f} "
      "per bar.")
    starts = sorted(str(s["trade_start"]) for s in sel)
    ends = sorted(str(s["last"]) for s in sel)
    w(f"- **Period:** trading starts once the window has filled "
      f"(mostly {stamp(starts[len(starts) // 2])}) and runs to the end of each "
      f"file (mostly {stamp(ends[len(ends) // 2])}).")
    w(f"- **Money and costs:** ${cfg['capital']:,.0f} per ticker, long only, "
      f"all in or all out, {cfg['cost_bps']:g} bps per buy or sell. The "
      f"portfolio splits ${cfg['capital']:,.0f} equally across all {n} "
      "tickers, and each part trades on its own.")
    w(f"- **Fit and fills:** refitted at "
      f"{'every bar' if cfg['step'] == 1 else 'every %d bars' % cfg['step']}. "
      "The decision uses bar t's close and a fit on bars up to t, and fills "
      "at the open of bar t + 1.")
    w("")

    w("## Summary\n")
    for r in combos:
        w(f"- **{r['combo']}:** the portfolio returns {pct(r['total_return'])} "
          f"(Sharpe {num(r['sharpe'])}, max drawdown {pct(r['max_drawdown'])}). "
          f"{pct(r['profitable'], 0)} of tickers make money and "
          f"{pct(r['beat_bh'], 0)} beat buy and hold. The median ticker "
          f"returns {pct(r['median_ticker_return'])}.")
    w(f"- **Buy and hold:** the portfolio returns {pct(bhp['total_return'])} "
      f"(Sharpe {num(bhp['sharpe'])}, max drawdown {pct(bhp['max_drawdown'])}). "
      f"{pct(bhp['profitable'], 0)} of tickers make money, and the median "
      f"ticker returns {pct(bhp['median_ticker_return'])}.")
    w(f"- **Per ticker, mean of the three combinations:** "
      f"{pct((mean_ret > 0).mean(), 0)} of tickers make money and "
      f"{pct((excess > 0).mean(), 0)} beat buy and hold. The median excess "
      f"over buy and hold is {pct(float(np.median(excess)))}.")
    a = np.array([[r[f"return_{f}"] for f in fields] for r in rank])
    same = np.mean(np.sign(a).min(axis=1) == np.sign(a).max(axis=1))
    w(f"- **Price fields agree:** the three fields give the same sign of "
      f"return for {pct(same, 0)} of tickers.")
    if flagged:
        w(f"- **Data flags:** {len(flagged)} tickers (marked ⚠) have a "
          f"bar-to-bar move above {pct(cfg['jump_flag'], 0)}, which may be a "
          "split, a reverse split or a bad tick rather than a real price move.")
    w("")

    w("## Portfolio\n")
    w(table(["combination", "final value", "return", "annual", "max DD",
             "Sharpe", "trades/ticker", "in market", "win rate",
             "tickers profitable", "beat B&H", "median ticker"],
            [[r["combo"], f"${r['final_value']:,.0f}", pct(r["total_return"]),
              pct(r["annual_return"]), pct(r["max_drawdown"]), num(r["sharpe"]),
              num(r["trades_per_ticker"], 0), pct(r["time_in_market"], 0),
              pct(r["win_rate"], 0), pct(r["profitable"], 0),
              pct(r["beat_bh"], 0) if r["combo"] != "buy & hold" else "–",
              pct(r["median_ticker_return"])] for r in combos + [bhp]]))
    w("\nSharpe uses daily portfolio returns, annualized with √252. Win rate "
      "is the share of round trips (buy, then sell) that made money.\n")

    w("## Stocks and ETFs\n")
    out = []
    for kind in ("stock", "etf", "unknown"):
        g = [r for r in rank if r["kind"] == kind]
        if not g:
            continue
        m = np.array([r["mean_return"] for r in g])
        b = np.array([r["bh_return"] for r in g])
        out.append([kind, len(g), pct(m.mean()), pct(float(np.median(m))),
                    pct((m > 0).mean(), 0), pct(b.mean()), pct(float(np.median(b))),
                    pct((m > b).mean(), 0)])
    w(table(["kind", "tickers", "mean return", "median return", "profitable",
             "B&H mean", "B&H median", "beat B&H"], out))
    w("")

    w("## Distribution of ticker returns\n")
    ps = (1, 5, 25, 50, 75, 95, 99)
    b = np.array([r["bh_return"] for r in rank])
    w(table(["", "mean"] + [f"P{p:02d}" for p in ps],
            [["strategy (mean of 3)", pct(mean_ret.mean())]
             + [pct(float(np.percentile(mean_ret, p))) for p in ps],
             ["buy & hold", pct(b.mean())]
             + [pct(float(np.percentile(b, p))) for p in ps],
             ["strategy − B&H", pct(excess.mean())]
             + [pct(float(np.percentile(excess, p))) for p in ps]]))
    w("")

    w("## Most profitable targets\n")
    w("Ranked by the mean return of the three combinations; `ranking.csv` "
      f"has all {n} tickers. Max DD, Sharpe, trades and time in market are "
      "means over the three combinations.\n")
    w(ranking_table(rank[:50], fields))
    w("")
    w("## Largest gain over buy and hold\n")
    w(ranking_table(sorted(rank, key=lambda r: -r["excess_vs_bh"])[:20], fields))
    w("")
    w("## Least profitable targets\n")
    w(ranking_table(rank[-20:], fields))
    w("")

    w("## Caveats\n")
    w("- **Selection bias:** the three combinations were chosen as the best "
      "of 216 on 30 tickers over this same period. Most of these tickers "
      "are new, but the dates are the same, so this is an out-of-sample test "
      "across tickers, not across time.")
    w("- **Ranking is in sample:** the top targets are ranked after the fact. "
      "A ticker that did well here is not shown to do well next period.")
    w("- **Costs and fills:** fills at the next bar's open with a flat cost "
      "per trade. Spreads, slippage and market impact on less liquid names "
      "are not modelled beyond that.")
    w("- **Prices:** dividends are ignored, prices may not be adjusted for "
      "splits (see the ⚠ flags), and the data may have survivorship bias.")
    w("")
    w(f"Run time {cfg['run_seconds']:.0f} s, modefinder {cfg['modefinder_version']}. "
      "The CSV files next to this report hold every number above.")

    path = os.path.join(out_dir, "report.md")
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
    return path


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    print(write_report(sys.argv[1]))
